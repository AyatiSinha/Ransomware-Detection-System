"""ML Anomaly Detector blending IsolationForest and RandomForestClassifier on behavioral features.

Adapted from Mangesh-Bhattacharya/Ransomware-Detection-System.
Note: Models are trained on synthetic data generated by this module; sandbox metrics
do not represent real-world detection accuracy.
"""

from pathlib import Path
from typing import Dict, List

import numpy as np

try:
    import joblib  # type: ignore
    from sklearn.ensemble import IsolationForest, RandomForestClassifier  # type: ignore
    SKLEARN_AVAILABLE = True
except ImportError:
    joblib = None  # type: ignore
    IsolationForest = None  # type: ignore
    RandomForestClassifier = None  # type: ignore
    SKLEARN_AVAILABLE = False

FEATURE_COLUMNS: List[str] = [
    "file_create_rate",
    "file_modify_rate",
    "file_rename_rate",
    "unique_extension_count",
    "avg_entropy",
    "max_entropy",
    "process_cpu",
]


def _generate_synthetic_dataset(n_samples: int = 400, seed: int = 42):
    rng = np.random.default_rng(seed)
    n_half = n_samples // 2

    # Benign file activity
    benign = np.column_stack([
        rng.uniform(0, 4, n_half),
        rng.uniform(0, 6, n_half),
        rng.uniform(0, 2, n_half),
        rng.integers(1, 3, n_half),
        rng.uniform(3.0, 5.2, n_half),
        rng.uniform(3.5, 5.8, n_half),
        rng.uniform(1.0, 20.0, n_half),
    ])
    # Ransomware-like synthetic activity
    malicious = np.column_stack([
        rng.uniform(10, 60, n_half),
        rng.uniform(15, 80, n_half),
        rng.uniform(10, 70, n_half),
        rng.integers(3, 15, n_half),
        rng.uniform(7.1, 7.99, n_half),
        rng.uniform(7.5, 8.0, n_half),
        rng.uniform(25.0, 95.0, n_half),
    ])

    X = np.vstack([benign, malicious])
    y = np.concatenate([np.zeros(n_half, dtype=int), np.ones(n_half, dtype=int)])
    return X, y


class MLAnomalyDetector:
    """Blends IsolationForest (unsupervised) and RandomForestClassifier (supervised) into a 0-100 risk score."""

    def __init__(self) -> None:
        self.iso_forest = None
        self.rf_clf = None
        self.is_fitted = False

    def fit(self) -> "MLAnomalyDetector":
        X, y = _generate_synthetic_dataset()
        if SKLEARN_AVAILABLE:
            self.iso_forest = IsolationForest(contamination=0.25, random_state=42)
            self.iso_forest.fit(X[y == 0])
            self.rf_clf = RandomForestClassifier(n_estimators=50, random_state=42)
            self.rf_clf.fit(X, y)
        self.is_fitted = True
        return self

    def assess(self, features: Dict[str, float]) -> dict:
        if not self.is_fitted:
            self.fit()

        vec = np.array([[float(features.get(col, 0.0)) for col in FEATURE_COLUMNS]])
        if SKLEARN_AVAILABLE and self.iso_forest is not None and self.rf_clf is not None:
            rf_prob = float(self.rf_clf.predict_proba(vec)[0][1])
            iso_score = float(self.iso_forest.decision_function(vec)[0])
            iso_risk = max(0.0, min(1.0, 0.5 - iso_score))
            risk_score = round((0.65 * rf_prob + 0.35 * iso_risk) * 100.0, 2)
        else:
            # Deterministic heuristic fallback when scikit-learn is not installed
            ent_norm = max(0.0, min(1.0, (float(features.get("max_entropy", 0.0)) - 5.0) / 3.0))
            rate_norm = max(0.0, min(1.0, float(features.get("file_modify_rate", 0.0)) / 20.0))
            ext_norm = max(0.0, min(1.0, float(features.get("unique_extension_count", 0.0)) / 5.0))
            risk_score = round((0.45 * ent_norm + 0.35 * rate_norm + 0.20 * ext_norm) * 100.0, 2)

        return {
            "risk_score": risk_score,
            "is_anomalous": risk_score >= 60.0,
            "sklearn_backend": SKLEARN_AVAILABLE,
        }

    def save(self, path: Path | str) -> Path:
        out = Path(path)
        out.parent.mkdir(parents=True, exist_ok=True)
        if joblib is not None and self.is_fitted:
            joblib.dump({"iso": self.iso_forest, "rf": self.rf_clf}, out)
        return out

    @classmethod
    def load(cls, path: Path | str) -> "MLAnomalyDetector":
        det = cls()
        p = Path(path)
        if joblib is not None and p.exists():
            data = joblib.load(p)
            det.iso_forest = data.get("iso")
            det.rf_clf = data.get("rf")
            det.is_fitted = True
        else:
            det.fit()
        return det
